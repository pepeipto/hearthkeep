local function setup(db)
  local HK = Stub.load("Hearthkeep")
  _G.Hearthkeep = HK
  HearthkeepDB = db
  HK.Storage.Load()
  return HK
end

test("the steps are language, look and preset; the defaults are English and Recommended", function()
  local HK = setup()
  eq(HK.Setup.STEPS, { "language", "look", "preset" })
  local state = HK.Setup.New()
  eq(state.step, 1)
  eq(state.language, "enUS")
  eq(state.skin, "blizzard")
  eq(state.preset, "recommended")
end)

test("choosing a language applies it at once and rejects unknown codes", function()
  local HK = setup()
  local state = HK.Setup.New()
  eq(HK.Setup.Choose(state, "language", "deDE"), true)
  eq(HK.db.settings.language, "deDE")
  eq(HK.L.COL_LEVEL, "Stufe")
  eq(HK.Setup.Choose(state, "language", "zhCN"), false)
  eq(state.language, "deDE")
end)

test("choosing a skin previews it and rejects unknown names", function()
  local HK = setup()
  local state = HK.Setup.New()
  eq(HK.Setup.Choose(state, "skin", "dark"), true)
  eq(HK.db.settings.skin, "dark")
  eq(HK.Setup.Choose(state, "skin", "ghost"), false)
  eq(state.skin, "dark")
end)

test("choosing a preset accepts only the known presets", function()
  local HK = setup()
  local state = HK.Setup.New()
  eq(HK.Setup.Choose(state, "preset", "minimal"), true)
  eq(state.preset, "minimal")
  eq(HK.Setup.Choose(state, "preset", "everything"), false)
  eq(state.preset, "minimal")
  eq(HK.Setup.Choose(state, "bogus", 1), false)
end)

test("Next walks the three steps and then returns nil", function()
  local HK = setup()
  local state = HK.Setup.New()
  eq(HK.Setup.Next(state), "look")
  eq(HK.Setup.Next(state), "preset")
  eq(HK.Setup.Next(state), nil)
end)

test("Finish applies language, skin and preset, marks setup done and opens the home window", function()
  local HK = setup()
  Stub.fire("PLAYER_LOGIN")
  HK:RegisterModule("Extra", { default = false, presets = { minimal = false, recommended = true } })
  local state = HK.Setup.New()
  HK.Setup.Choose(state, "language", "esES")
  HK.Setup.Choose(state, "skin", "parchment")
  HK.Setup.Finish(state)
  eq(HK.db.settings.setupDone, true)
  eq(HK.db.settings.language, "esES")
  eq(HK.db.settings.skin, "parchment")
  truthy(HK:IsModuleEnabled("Extra"))
  truthy(HK.Home.frame:IsShown())
  falsy(HK.Setup.IsShown())
end)

test("Finish with the minimal preset leaves the optional modules off", function()
  local HK = setup()
  Stub.fire("PLAYER_LOGIN")
  HK:RegisterModule("Extra", { default = false, presets = { minimal = false, recommended = true } })
  local state = HK.Setup.New()
  HK.Setup.Choose(state, "preset", "minimal")
