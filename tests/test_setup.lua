test("Skip keeps English, marks setup done and it does not auto-open again", function()
  local HK = setup()
  eq(HK.Setup.ShouldAutoOpen(), true)
  HK.Setup.Skip()
  eq(HK.db.settings.setupDone, true)
  eq(HK.db.settings.language, "enUS")
  eq(HK.Setup.ShouldAutoOpen(), false)
end)

test("SuggestLanguage maps esMX to esES and returns nil for enUS and frFR", function()
  local HK = setup()
  for client, expected in pairs({ esES = "esES", esMX = "esES", deDE = "deDE" }) do
    Stub.locale = client
    eq(HK.Setup.SuggestLanguage(), expected)
  end
  for _, client in ipairs({ "enUS", "frFR" }) do
    Stub.locale = client
    eq(HK.Setup.SuggestLanguage(), nil)
  end
end)

test("the assistant never switches language by itself on an esES client", function()
  local HK = setup()
  Stub.locale = "esES"
  HK.Setup.Open()
  eq(HK.db.settings.language, "enUS")
  eq(HK.Setup.New().language, "enUS")
end)

test("Open creates the frame once; Close hides it and Open reuses it from the first step", function()
  local HK = setup()
  eq(HK.Setup.frame, nil)
  HK.Setup.Open()
  local frame = HK.Setup.frame
  truthy(frame)
  truthy(HK.Setup.IsShown())
  local created = #Stub.frames
  local tracked = 0
  local track = HK.Skins.Track
  HK.Skins.Track = function(...) tracked = tracked + 1 return track(...) end
  frame.next.scripts.OnClick()
  eq(frame.state.step, 2)
  HK.Setup.Close()
  eq(HK.Setup.frame, frame)
  falsy(HK.Setup.IsShown())
  SlashCmdList.HEARTHKEEP("setup")
  eq(HK.Setup.frame, frame)
  truthy(HK.Setup.IsShown())
  eq(frame.state.step, 1)
  eq(#Stub.frames, created)
  eq(tracked, 0)
end)

test("Finish and Skip hide the assistant without dropping the frame", function()
  local HK = setup()
  Stub.fire("PLAYER_LOGIN")
  HK.Setup.Open()
  local frame = HK.Setup.frame
  HK.Setup.Skip()
  falsy(HK.Setup.IsShown())
  HK.Setup.Open()
  HK.Setup.Finish(frame.state)
  eq(HK.Setup.frame, frame)
  falsy(HK.Setup.IsShown())
end)

test("PLAYER_LOGIN opens the assistant on a fresh install even with Modes off", function()
  local HK = setup({ settings = { modules = { Modes = false } } })
  Stub.fire("PLAYER_LOGIN")
  truthy(HK.Setup.frame)
end)

test("PLAYER_LOGIN does not open the assistant once setup is done", function()
  local HK = setup({ settings = { setupDone = true } })
  Stub.fire("PLAYER_LOGIN")
  eq(HK.Setup.frame, nil)
end)

test("/hk setup opens the assistant", function()
  local HK = setup()
