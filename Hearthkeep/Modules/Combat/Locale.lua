local _, HK = ...

-- Strings for the combat-group modules (Threat, Buffs) and the Macros checker.
-- Macro condition phrases are kept as nested tables and flattened into keys:
--   cond = { base, baseNot, withArg, withArgNot }  ->  MAC_C_<KEY>, MAC_C_<KEY>_NOT,
--   MAC_C_<KEY>_ARG, MAC_C_<KEY>_ARG_NOT  (the last two use %s for the argument).
-- Unit predicates (help, harm, exists, dead, party, raid) have no subject; the checker
-- adds one ("it" / "your target"). Player predicates carry their own subject.

local function flatten(conds)
  local out = {}
  for key, list in pairs(conds) do
    local base = "MAC_C_" .. key:upper()
    out[base] = list[1]
    out[base .. "_NOT"] = list[2]
    if list[3] then
      out[base .. "_ARG"] = list[3]
      out[base .. "_ARG_NOT"] = list[4]
    end
  end
  return out
end

local function register(locale, strings, conds)
  HK.Locale.Register(locale, strings)
  HK.Locale.Register(locale, flatten(conds))
end

